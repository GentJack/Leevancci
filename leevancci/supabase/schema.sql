-- Remove EVERY old policy on the shop tables first (a leftover "allow all" or
-- "users can update their profile" policy from an earlier setup would let a
-- customer edit prices, orders or make themselves admin). The policies below
-- are the complete, correct set.
do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies
           where schemaname = 'public'
             and tablename in ('profiles','products','orders','order_items','store_settings','newsletter_subscribers','contact_messages')
  loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

-- profiles: you can read your own; admins read all. Nobody can edit is_admin from the app.
drop policy if exists "profiles read"   on public.profiles;
create policy "profiles read" on public.profiles for select using (id = auth.uid() or public.is_admin());

-- products: public sees active ones; admins do everything
drop policy if exists "products read"   on public.products;
drop policy if exists "products admin write" on public.products;
create policy "products read" on public.products for select using (is_active or public.is_admin());
create policy "products admin write" on public.products for all using (public.is_admin()) with check (public.is_admin());

-- orders: customers read their own; admins read + update status. Inserts only via create_order().
drop policy if exists "orders read"   on public.orders;
drop policy if exists "orders admin update" on public.orders;
create policy "orders read" on public.orders for select using (user_id = auth.uid() or public.is_admin());
create policy "orders admin update" on public.orders for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "order_items read" on public.order_items;
create policy "order_items read" on public.order_items for select using (
  exists (select 1 from public.orders o where o.id = order_id and (o.user_id = auth.uid() or public.is_admin()))
);

-- settings: public read, admin edit
drop policy if exists "settings read"  on public.store_settings;
drop policy if exists "settings admin" on public.store_settings;
create policy "settings read"  on public.store_settings for select using (true);
create policy "settings admin" on public.store_settings for update using (public.is_admin()) with check (public.is_admin());

-- newsletter / contact: anyone may submit, only admins read
drop policy if exists "newsletter insert" on public.newsletter_subscribers;
drop policy if exists "newsletter admin"  on public.newsletter_subscribers;
create policy "newsletter insert" on public.newsletter_subscribers for insert
  with check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' and length(email) <= 254);
create policy "newsletter admin" on public.newsletter_subscribers for select using (public.is_admin());

drop policy if exists "contact insert" on public.contact_messages;
drop policy if exists "contact admin"  on public.contact_messages;
create policy "contact insert" on public.contact_messages for insert
  with check (length(name) between 1 and 120 and length(message) between 1 and 4000
              and email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$');
create policy "contact admin" on public.contact_messages for all using (public.is_admin()) with check (public.is_admin());

-- ---------- create_order(): all money maths happens here --------------
-- p_items   = [{"id": 3, "size": "40", "qty": 1}, ...]
-- p_address = {"name","phone","line1","suburb","city","province","postal_code","country"}
create or replace function public.create_order(p_items jsonb, p_address jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid   uuid := auth.uid();
  v_email text;
  v_set   public.store_settings%rowtype;
  v_sub   integer := 0;
  v_ship  integer;
  v_total integer;
  v_oid   bigint;
  v_ref   text;
  it      jsonb;
  p       public.products%rowtype;
  q       integer;
  sz      text;
  need    jsonb := '{}'::jsonb;   -- product id -> total qty requested (stock check)
begin
  if v_uid is null then raise exception 'Please log in to place an order.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0
     or jsonb_array_length(p_items) > 40 then
    raise exception 'Your cart is empty.';
  end if;
  if coalesce(p_address->>'name','') = '' or coalesce(p_address->>'line1','') = ''
     or coalesce(p_address->>'city','') = '' or coalesce(p_address->>'phone','') = '' then
    raise exception 'Please complete your delivery details.';
  end if;

  select * into v_set from public.store_settings where id = 1;
  select email into v_email from auth.users where id = v_uid;

  -- pass 1: validate + total
  for it in select * from jsonb_array_elements(p_items) loop
    q  := (it->>'qty')::integer;
    sz := nullif(it->>'size','');
    if q is null or q < 1 or q > 10 then raise exception 'Invalid quantity.'; end if;
    select * into p from public.products where id = (it->>'id')::bigint and is_active;
    if not found then raise exception 'An item in your cart is no longer available.'; end if;
    if p.sizes is not null and array_length(p.sizes,1) > 0 and (sz is null or not (sz = any(p.sizes))) then
      raise exception 'Please choose a valid size for %.', p.name;
    end if;
    need := jsonb_set(need, array[p.id::text], to_jsonb(coalesce((need->>p.id::text)::integer,0) + q));
    if p.stock is not null and (need->>p.id::text)::integer > p.stock then
      raise exception 'Sorry, % is out of stock (only % left).', p.name, p.stock;
    end if;
    v_sub := v_sub + p.price_cents * q;
  end loop;

  v_ship  := case when v_sub >= v_set.free_shipping_threshold_cents then 0 else v_set.shipping_cents end;
  v_total := v_sub + v_ship;
  v_ref   := 'LV-' || upper(encode(gen_random_bytes(5), 'hex'));

  insert into public.orders (user_id, status, subtotal_cents, shipping_cents, total_cents,
                             shipping_address, reference, customer_email)
  values (v_uid, 'pending', v_sub, v_ship, v_total, p_address, v_ref, v_email)
  returning id into v_oid;

  -- pass 2: line items at the DATABASE price
  for it in select * from jsonb_array_elements(p_items) loop
    select * into p from public.products where id = (it->>'id')::bigint;
    insert into public.order_items (order_id, product_id, product_name, unit_price_cents, quantity, size)
    values (v_oid, p.id, p.name, p.price_cents, (it->>'qty')::integer, nullif(it->>'size',''));
  end loop;

  return jsonb_build_object('id', v_oid, 'reference', v_ref, 'total_cents', v_total,
                            'subtotal_cents', v_sub, 'shipping_cents', v_ship, 'email', v_email);
end $$;

-- give a customer a fresh Paystack reference to retry an unpaid order
create or replace function public.renew_order_reference(p_order bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_ref text; o public.orders%rowtype;
begin
  select * into o from public.orders where id = p_order and user_id = auth.uid() and status = 'pending';
  if not found then raise exception 'Order not found or already paid.'; end if;
  v_ref := 'LV-' || upper(encode(gen_random_bytes(5), 'hex'));
  update public.orders set reference = v_ref where id = o.id;
  return jsonb_build_object('id', o.id, 'reference', v_ref, 'total_cents', o.total_cents, 'email', o.customer_email);
end $$;

-- ---------- mark_order_paid(): server only (service_role) -------------
create or replace function public.mark_order_paid(p_reference text, p_paystack_ref text, p_amount_cents integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype; li record;
begin
  select * into o from public.orders where reference = p_reference for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'order_not_found'); end if;
  if o.status <> 'pending' then return jsonb_build_object('ok', true, 'already', true, 'id', o.id); end if;
  if o.total_cents <> p_amount_cents then return jsonb_build_object('ok', false, 'error', 'amount_mismatch'); end if;

  update public.orders set status = 'paid', paid_at = now(), paystack_reference = p_paystack_ref where id = o.id;
  for li in select product_id, quantity from public.order_items where order_id = o.id and product_id is not null loop
    update public.products set stock = greatest(stock - li.quantity, 0) where id = li.product_id and stock is not null;
  end loop;
  return jsonb_build_object('ok', true, 'id', o.id);
end $$;

revoke all on function public.mark_order_paid(text, text, integer) from public, anon, authenticated;
grant execute on function public.mark_order_paid(text, text, integer) to service_role;
revoke all on function public.create_order(jsonb, jsonb) from public, anon;
grant execute on function public.create_order(jsonb, jsonb) to authenticated;
revoke all on function public.renew_order_reference(bigint) from public, anon;
grant execute on function public.renew_order_reference(bigint) to authenticated;

